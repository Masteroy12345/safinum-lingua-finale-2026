_UI_CACHE: dict[tuple[str, str, str], str] = {}
_PH_RE = re.compile(r"\{[a-z_]+\}")


def _extract_placeholders(text: str) -> list[str]:
    return sorted(set(_PH_RE.findall(str(text or ""))))


def _fit_max_chars(val: str, max_chars: int | None) -> str:
    if not max_chars or len(val) <= max_chars:
        return val
    # Ne jamais couper au milieu d'un emplacement {placeholder}
    if _PH_RE.search(val):
        return val
    return val[:max_chars].rstrip()


def _translate_unseen_ui_string(source_text: str, lang: str, max_chars: int | None) -> str:
    """Traduit une clé UI inédite tout en conservant exactement les emplacements {placeholder}."""
    phs = _PH_RE.findall(source_text)
    masked = source_text
    for idx, ph in enumerate(phs):
        masked = masked.replace(ph, f"__PH{idx}__", 1)
    res = translate_phrase(masked, lang)["translated"]
    for idx, ph in enumerate(phs):
        res = res.replace(f"__PH{idx}__", ph)
    # Vérifier que tous les placeholders sont présents
    if _extract_placeholders(res) != _extract_placeholders(source_text):
        return source_text
    if UI_PHONETIC_TTS:
        res = to_web_phonetic_safe(res, lang)
    return _fit_max_chars(res, max_chars)


def handle_ui_translation(payload: dict[str, Any], fallback_lang: str = "fr") -> dict[str, Any]:
    """Traite une requête Mobile/Web `type == 'ui_translation'` selon le contrat officiel Safinum."""
    raw_lang = payload.get("language")
    source_strings = payload.get("strings") or {}

    lang = normalize_language(raw_lang)
    if not lang:
        sample_text = " ".join(
            str((entry or {}).get("text", ""))
            for entry in list(source_strings.values())[:5]
        )
        lang = detect_language(sample_text, fallback=fallback_lang or "fr")

    if lang not in SUPPORTED_LANGUAGES:
        lang = "fr"

    lang_table = UI_TRANSLATIONS.get(lang, UI_TRANSLATIONS["fr"])
    translated_strings: dict[str, str] = {}

    for key, entry in source_strings.items():
        if isinstance(entry, dict):
            src_text = str(entry.get("text") or "")
            max_chars = entry.get("max_chars")
        else:
            src_text = str(entry or "")
            max_chars = None

        cache_key = (lang, key, src_text)
        if cache_key in _UI_CACHE:
            val = _UI_CACHE[cache_key]
        elif key in lang_table:
            val = lang_table[key]
            if UI_PHONETIC_TTS and lang not in ("fr", "en"):
                val = to_web_phonetic_safe(val, lang)
            # Vérifier intégrité des placeholders par rapport à la source
            if _extract_placeholders(val) != _extract_placeholders(src_text):
                val = src_text
            val = _fit_max_chars(val, max_chars)
            _UI_CACHE[cache_key] = val
        else:
            val = _translate_unseen_ui_string(src_text, lang, max_chars)
            _UI_CACHE[cache_key] = val

        translated_strings[key] = val

    return {
        "language": lang,
        "strings": translated_strings,
    }
